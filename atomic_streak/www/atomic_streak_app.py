"""Serves the Atomic Streak app (a PWA) at /atomic-streak and /atomic-streak/<anything>.

atomic_streak_app.html is generated by `frontend/scripts/make-page.mjs` during the frontend
build. Signed-out visitors get the same page; the app shows its own sign-in screen, which signs
in through Frappe's standard /api/method/login (same users, passwords and sessions).
"""

import frappe

no_cache = 1


def get_context(context):
	# the app posts to whitelisted methods, so it needs this session's CSRF token
	csrf_token = frappe.sessions.get_csrf_token()
	frappe.db.commit()  # get_csrf_token may have written the session
	context.csrf_token = csrf_token
	context.is_guest = 1 if frappe.session.user == "Guest" else 0
	context.no_cache = 1
	return context
